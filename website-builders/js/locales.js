class WBi18n {
  constructor() {
    this.currentLang = localStorage.getItem('wb_portal_lang') || 'en';
    this.init();
  }

  init() {
    this.applyLanguage(this.currentLang);
  }

  setLanguage(lang) {
    if (!window.WB_LOCALES[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('wb_portal_lang', lang);
    this.applyLanguage(lang);
    document.dispatchEvent(new CustomEvent('wb:languageChanged', { detail: { lang } }));
  }

  t(key, fallback = '') {
    const dict = window.WB_LOCALES[this.currentLang] || window.WB_LOCALES.en;
    return dict[key] || fallback || key;
  }

  applyLanguage(lang) {
    const dict = window.WB_LOCALES[lang] || window.WB_LOCALES.en;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          if (el.placeholder) el.placeholder = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });

    const langSelect = document.getElementById('wb-language-select');
    if (langSelect) {
      langSelect.value = lang;
    }
  }
}

window.i18n = new WBi18n();
